"""
DDL для market_data_session — дневные бары ОСНОВНОЙ сессии, собранные из 5-минуток.

Зачем (аудит 26.09.2026, находки F1, F2, F13). Дневная свеча брокера — это весь
торговый день: open — первая сделка утренней сессии (06:55), close — закрытие
вечерней (23:45). На ней модель училась «ночи» 23:45→06:55, когда биржа закрыта,
а робот держит позицию 18:40→09:10. Корреляция этих доходностей +0,43. Вдобавок
определение open внутри выборки дважды менялось: 09:55 до июля 2024, 07:00 с
августа 2024, 06:55 с февраля 2025.

Бар основной сессии снимает все три проблемы разом:
  open  = первая сделка основной сессии (10:00 до 14.09.2026, 09:10 с 14.09) —
          момент, в который CLOSE закрывал и закрывает ночные позиции;
  close = последняя сделка до 18:40 — момент ночного входа;
  high/low/volume — внутри основной сессии.
Тогда overnight = open(D+1)/close(D) — ровно торгуемое окно 18:40→09:10 вместе с
вечерней и утренней сессиями, а intraday = close/open — окно шорта 09:10→18:40.

И ещё: в 18:38 бар текущего дня уже есть (частичный, по последнюю 5-минутку),
поэтому прогноз ночи строится от сегодняшнего бара, а не от вчерашнего.
Прежний контур прогнозировал уже случившуюся ночь и вычитал из неё утренний гэп
(F1) — отсюда рейтинг, коррелированный с −гэпом на −0,9…−1,0.

complete = бар дошёл до последней 5-минутки перед 18:40 (частичный бар дня
перезаписывается следующим прогоном).
"""

CREATE_SESSION_SQL = """
CREATE TABLE IF NOT EXISTS market_data_session (
    ticker     VARCHAR(10)    NOT NULL,
    date       DATE           NOT NULL,
    open       NUMERIC(18, 4) NOT NULL,
    high       NUMERIC(18, 4) NOT NULL,
    low        NUMERIC(18, 4) NOT NULL,
    close      NUMERIC(18, 4) NOT NULL,
    volume     BIGINT         NOT NULL DEFAULT 0,
    n_bars     INTEGER        NOT NULL,
    complete   BOOLEAN        NOT NULL DEFAULT FALSE,
    updated_at TIMESTAMPTZ    NOT NULL DEFAULT NOW(),
    CONSTRAINT pk_market_data_session PRIMARY KEY (ticker, date)
);
"""
